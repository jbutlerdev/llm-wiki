/**
 * Wiki configuration module
 * @module @llm-wiki/core/config
 */

import { readFile, writeFile } from 'fs/promises';
import { existsSync } from 'fs';
import { join } from 'path';
import matter from 'gray-matter';
import type { WikiConfig } from '../types/index.js';

/**
 * Default configuration values
 */
const DEFAULT_CONFIG: WikiConfig = {
  wikiDir: './wiki',
  rawDir: './wiki/raw',
  qmdDir: './.llm-wiki',
  name: 'LLM Wiki',
  description: 'A personal knowledge base powered by LLM',
  schemaPath: './wiki/CLAUDE.md',
};

/**
 * Load wiki configuration from config file
 */
export async function loadConfig(wikiDir: string): Promise<WikiConfig> {
  const configPath = join(wikiDir, 'llm-wiki.yml');
  const legacyPath = join(wikiDir, 'wiki', 'config.md');

  // Try YAML config first
  if (existsSync(configPath)) {
    try {
      const content = await readFile(configPath, 'utf-8');
      // Simple YAML parsing for basic key-value pairs
      const config: Record<string, string> = {};
      const lines = content.split('\n');
      
      for (const line of lines) {
        const trimmed = line.trim();
        if (trimmed && !trimmed.startsWith('#')) {
          const colonIndex = trimmed.indexOf(':');
          if (colonIndex > 0) {
            const key = trimmed.slice(0, colonIndex).trim();
            const value = trimmed.slice(colonIndex + 1).trim().replace(/^["']|["']$/g, '');
            config[key] = value;
          }
        }
      }

      return {
        wikiDir: config.wikiDir || DEFAULT_CONFIG.wikiDir,
        rawDir: config.rawDir || DEFAULT_CONFIG.rawDir,
        qmdDir: config.qmdDir || DEFAULT_CONFIG.qmdDir,
        name: config.name || DEFAULT_CONFIG.name,
        description: config.description || DEFAULT_CONFIG.description,
        schemaPath: config.schemaPath || DEFAULT_CONFIG.schemaPath,
      };
    } catch {
      // Fall through to defaults
    }
  }

  // Try markdown config (legacy)
  if (existsSync(legacyPath)) {
    try {
      const content = await readFile(legacyPath, 'utf-8');
      const { data } = matter(content);

      return {
        wikiDir: data.wikiDir || DEFAULT_CONFIG.wikiDir,
        rawDir: data.rawDir || DEFAULT_CONFIG.rawDir,
        qmdDir: data.qmdDir || DEFAULT_CONFIG.qmdDir,
        name: data.name || DEFAULT_CONFIG.name,
        description: data.description || DEFAULT_CONFIG.description,
        schemaPath: data.schemaPath || DEFAULT_CONFIG.schemaPath,
      };
    } catch {
      // Fall through to defaults
    }
  }

  // Return defaults
  return { ...DEFAULT_CONFIG };
}

/**
 * Save wiki configuration to config file
 */
export async function saveConfig(wikiDir: string, config: Partial<WikiConfig>): Promise<void> {
  const configPath = join(wikiDir, 'llm-wiki.yml');

  // Merge with defaults
  const fullConfig: WikiConfig = {
    ...DEFAULT_CONFIG,
    ...config,
  };

  // Write as YAML
  const yaml = `# LLM Wiki Configuration
# Generated by LLM Wiki

wikiDir: "${fullConfig.wikiDir}"
rawDir: "${fullConfig.rawDir}"
qmdDir: "${fullConfig.qmdDir}"
name: "${fullConfig.name}"
description: "${fullConfig.description}"
schemaPath: "${fullConfig.schemaPath}"
`;

  await writeFile(configPath, yaml, 'utf-8');
}

/**
 * Get default configuration
 */
export function getDefaultConfig(): WikiConfig {
  return { ...DEFAULT_CONFIG };
}
