/**
 * Integration tests for full ingest flow
 * Tests the complete workflow: source → wiki page → search → query
 * 
 * Phase 14: Testing & QA
 */
import { describe, it, expect, beforeEach, afterEach, beforeAll } from 'vitest';
import { join } from 'path';
import { existsSync } from 'fs';
import { mkdir, rm, writeFile, readFile, readdir } from 'fs/promises';
import { tmpdir } from 'os';
import { init } from '../packages/core/dist/wiki/init.js';
import { ingest } from '../packages/core/dist/source/ingest.js';
import { listPages } from '../packages/core/dist/wiki/list.js';
import { createQMDStore, searchWiki, indexWiki } from '../packages/core/dist/qmd/index.js';

describe('Full Ingest Flow Integration', () => {
  let testWikiDir: string;

  beforeEach(async () => {
    testWikiDir = join(tmpdir(), `llm-wiki-integration-${Date.now()}-${Math.random()}`);
    await mkdir(testWikiDir, { recursive: true });
    await init(testWikiDir);
  });

  afterEach(async () => {
    try {
      await rm(testWikiDir, { recursive: true, force: true });
    } catch {
      // Ignore cleanup errors
    }
  });

  describe('source → wiki page', () => {
    it('should ingest a source and create a wiki page', async () => {
      // Create a test source
      const sourcePath = join(testWikiDir, 'test-document.md');
      const sourceContent = `# Test Document
      
This is a test document about TypeScript programming.

## Key Points
- TypeScript is a typed superset of JavaScript
- It compiles to plain JavaScript
- It adds optional static typing

## More Information
TypeScript was developed by Microsoft.`;
      await writeFile(sourcePath, sourceContent);

      // Ingest the source
      const result = await ingest(sourcePath, {
        wikiDir: testWikiDir,
        rawDir: join(testWikiDir, 'wiki', 'raw'),
      });

      expect(result.success).toBe(true);
      expect(result.pagesCreated.length).toBeGreaterThan(0);

      // Verify source page was created
      const sourcePagePath = join(testWikiDir, 'wiki', 'source', `${result.source!.checksum}.md`);
      expect(existsSync(sourcePagePath)).toBe(true);

      const pageContent = await readFile(sourcePagePath, 'utf-8');
      expect(pageContent).toContain('Test Document');
      expect(pageContent).toContain('TypeScript');
    });

    it('should copy source to raw directory', async () => {
      const sourcePath = join(testWikiDir, 'raw-test.md');
      await writeFile(sourcePath, '# Raw Test\n\nContent for raw directory.');

      const result = await ingest(sourcePath, {
        wikiDir: testWikiDir,
        rawDir: join(testWikiDir, 'wiki', 'raw'),
      });

      expect(result.success).toBe(true);
      
      // Verify source was copied to raw directory
      // The filename is generated by SourceLoader.generateStorageFilename (timestamp-title format)
      const rawDir = join(testWikiDir, 'wiki', 'raw');
      const files = await readdir(rawDir);
      expect(files.length).toBeGreaterThan(0);
      
      // Verify the content matches
      const rawFileContent = await readFile(join(rawDir, files[0]), 'utf-8');
      expect(rawFileContent).toContain('# Raw Test');
    });

    it('should create entity pages for mentioned concepts', async () => {
      const sourcePath = join(testWikiDir, 'concepts.md');
      await writeFile(sourcePath, `# Concept Document

This document mentions TypeScript, JavaScript, and Node.js.
These are important technologies for web development.`);
      await writeFile(join(testWikiDir, 'test-entity.md'), '# Additional Test\n\nMore TypeScript content.');

      // Ingest sources
      await ingest(sourcePath, {
        wikiDir: testWikiDir,
        rawDir: join(testWikiDir, 'wiki', 'raw'),
      });

      await ingest(join(testWikiDir, 'test-entity.md'), {
        wikiDir: testWikiDir,
        rawDir: join(testWikiDir, 'wiki', 'raw'),
      });

      // List all pages
      const pages = await listPages(testWikiDir);

      // Should have entity pages or at least the source pages
      expect(pages.length).toBeGreaterThan(0);
    });
  });

  describe('cross-reference updates', () => {
    it('should update index.md after ingestion', async () => {
      const sourcePath = join(testWikiDir, 'indexed.md');
      await writeFile(sourcePath, '# Indexed Document\n\nImportant content for indexing.');

      await ingest(sourcePath, {
        wikiDir: testWikiDir,
        rawDir: join(testWikiDir, 'wiki', 'raw'),
      });

      const indexPath = join(testWikiDir, 'wiki', 'index.md');
      const indexContent = await readFile(indexPath, 'utf-8');
      
      expect(indexContent).toContain('Indexed Document');
    });

    it('should maintain log of ingestions', async () => {
      const sourcePath = join(testWikiDir, 'logged.md');
      await writeFile(sourcePath, '# Logged Document\n\nThis should appear in log.');

      await ingest(sourcePath, {
        wikiDir: testWikiDir,
        rawDir: join(testWikiDir, 'wiki', 'raw'),
      });

      const logPath = join(testWikiDir, 'wiki', 'log.md');
      const logContent = await readFile(logPath, 'utf-8');
      
      expect(logContent).toContain('Logged Document');
      expect(logContent).toMatch(/\d{4}-\d{2}-\d{2}/); // Date format
    });
  });

  describe('search integration', () => {
    it('should make ingested content searchable', async () => {
      const sourcePath = join(testWikiDir, 'searchable.md');
      await writeFile(sourcePath, '# Searchable Document\n\nThis contains unique searchable content XYZ123.');

      await ingest(sourcePath, {
        wikiDir: testWikiDir,
        rawDir: join(testWikiDir, 'wiki', 'raw'),
      });

      // Note: Full search requires QMD to be set up
      // This test verifies the ingest pipeline works up to the point where search becomes possible
      const pages = await listPages(testWikiDir);
      expect(pages.some(p => p.title.includes('Searchable'))).toBe(true);
    });

    it('should index pages for search', async () => {
      const sourcePath = join(testWikiDir, 'indexed-search.md');
      await writeFile(sourcePath, '# Search Index Test\n\nContent for search indexing test ABC456.');

      await ingest(sourcePath, {
        wikiDir: testWikiDir,
        rawDir: join(testWikiDir, 'wiki', 'raw'),
      });

      // Verify wiki directory structure is maintained
      const wikiDir = join(testWikiDir, 'wiki');
      const files = await readdir(wikiDir, { recursive: true });
      expect(files.length).toBeGreaterThan(0);
    });
  });

  describe('error recovery', () => {
    it('should handle partial failures gracefully', async () => {
      const goodSource = join(testWikiDir, 'good.md');
      await writeFile(goodSource, '# Good Document\n\nThis should succeed.');

      // First ingest should succeed
      const result1 = await ingest(goodSource, {
        wikiDir: testWikiDir,
        rawDir: join(testWikiDir, 'wiki', 'raw'),
      });
      expect(result1.success).toBe(true);

      // Second ingest of same file should be idempotent
      const result2 = await ingest(goodSource, {
        wikiDir: testWikiDir,
        rawDir: join(testWikiDir, 'wiki', 'raw'),
      });
      expect(result2.success).toBe(true);
      expect(result2.source!.checksum).toBe(result1.source!.checksum);
    });

    it('should continue after single source failure', async () => {
      const validSource = join(testWikiDir, 'valid.md');
      await writeFile(validSource, '# Valid Source\n\nThis is valid.');

      // This should succeed
      const result = await ingest(validSource, {
        wikiDir: testWikiDir,
        rawDir: join(testWikiDir, 'wiki', 'raw'),
      });
      
      expect(result.success).toBe(true);
      expect(result.pagesCreated.length).toBeGreaterThan(0);
    });
  });

  describe('concurrent operations', () => {
    it('should handle multiple concurrent ingests', async () => {
      const sources = [
        { name: 'doc1.md', content: '# Document One\n\nContent for doc one.' },
        { name: 'doc2.md', content: '# Document Two\n\nContent for doc two.' },
        { name: 'doc3.md', content: '# Document Three\n\nContent for doc three.' },
      ];

      for (const { name, content } of sources) {
        await writeFile(join(testWikiDir, name), content);
      }

      // Ingest all sources
      const results = await Promise.all(
        sources.map(({ name }) => 
          ingest(join(testWikiDir, name), {
            wikiDir: testWikiDir,
            rawDir: join(testWikiDir, 'wiki', 'raw'),
          })
        )
      );

      // All should succeed
      expect(results.every(r => r.success)).toBe(true);
      expect(results.every(r => r.pagesCreated.length > 0)).toBe(true);
    });
  });
});

describe('Idempotency Tests', () => {
  let testWikiDir: string;

  beforeEach(async () => {
    testWikiDir = join(tmpdir(), `llm-wiki-idempotent-${Date.now()}-${Math.random()}`);
    await mkdir(testWikiDir, { recursive: true });
    await init(testWikiDir);
  });

  afterEach(async () => {
    try {
      await rm(testWikiDir, { recursive: true, force: true });
    } catch {
      // Ignore cleanup errors
    }
  });

  it('should produce same result when ingesting same source twice', async () => {
    const sourcePath = join(testWikiDir, 'idempotent.md');
    await writeFile(sourcePath, '# Idempotent Test\n\nSame content each time.');

    const result1 = await ingest(sourcePath, {
      wikiDir: testWikiDir,
      rawDir: join(testWikiDir, 'wiki', 'raw'),
    });

    const result2 = await ingest(sourcePath, {
      wikiDir: testWikiDir,
      rawDir: join(testWikiDir, 'wiki', 'raw'),
    });

    // Both should succeed
    expect(result1.success).toBe(true);
    expect(result2.success).toBe(true);

    // Checksum should match (same content)
    expect(result1.source!.checksum).toBe(result2.source!.checksum);
  });

  it('should update existing page on re-ingest', async () => {
    const sourcePath = join(testWikiDir, 'update-test.md');
    await writeFile(sourcePath, '# Update Test v1\n\nOriginal content.');

    const result1 = await ingest(sourcePath, {
      wikiDir: testWikiDir,
      rawDir: join(testWikiDir, 'wiki', 'raw'),
    });

    // Modify the file
    await writeFile(sourcePath, '# Update Test v2\n\nModified content.');

    const result2 = await ingest(sourcePath, {
      wikiDir: testWikiDir,
      rawDir: join(testWikiDir, 'wiki', 'raw'),
    });

    // Both should succeed
    expect(result1.success).toBe(true);
    expect(result2.success).toBe(true);

    // Checksums should differ (content changed)
    expect(result1.source!.checksum).not.toBe(result2.source!.checksum);
  });
});
